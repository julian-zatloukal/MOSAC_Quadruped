#!/usr/bin/env python3
"""Writes Src/gait_params.h from the walk parameters of Programmed_Yaw.

The parameters are loaded with motion_core.load_walk_params(), exactly as the Webots controller loads them:
Programmed_Gait_V2/gait_params.json over the gait_config defaults, then Programmed_Yaw/walk_params.json over that.

    python3 tools/gen_params.py            write Src/gait_params.h
    python3 tools/gen_params.py --check    exit 1 if Src/gait_params.h is out of date
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
YAW_DIR = os.path.join(REPO, "Webots", "controllers", "Programmed_Yaw")
HEADER = os.path.normpath(os.path.join(HERE, "..", "Src", "gait_params.h"))


def load():
    sys.path.insert(0, YAW_DIR)
    from motion_core import load_walk_params  # noqa: E402
    return load_walk_params()


def render():
    gait, walk = load()
    if gait["backward"] or not gait["finish_stages"]:
        raise SystemExit("gen_params: the C port walks forward with finish_stages on only")
    # yaw_kp / yaw_ki / turn_max are not exported: the heading loop needs the simulator's yaw (see gait.h).
    w =[gait[k] for k in ("weight_lean", "weight_swing", "weight_restore", "weight_push")]
    lines = [
        "/* Generated by tools/gen_params.py - do not edit; run `make params` after changing the JSON files.",
        " * Source: Webots/controllers/Programmed_Yaw/walk_params.json laid over",
        " *         Webots/controllers/Programmed_Gait_V2/gait_params.json (motion_core.load_walk_params). */",
        "#ifndef GAIT_RUNNER_GAIT_PARAMS_H",
        "#define GAIT_RUNNER_GAIT_PARAMS_H",
        "",
        "#define GAIT_WALK_PARAMS { \\",
        f"    .period          = {gait['gait_period']!r}, \\",
        f"    .weight          = {{ {w[0]!r}, {w[1]!r}, {w[2]!r}, {w[3]!r} }}, \\",
        f"    .ramp_cycles     = {float(walk['ramp_cycles'])!r}, \\",
        f"    .standing_height = {float(gait['standing_height'])!r}f, \\",
        f"    .parabola_height = {float(gait['parabola_height'])!r}f, \\",
        f"    .parabola_length = {float(gait['parabola_length'])!r}f, \\",
        f"    .lean_primary    = {float(gait['lean_primary'])!r}f, \\",
        f"    .lean_secondary  = {float(gait['lean_secondary'])!r}f, \\",
        "}",
        "",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only check that the header is up to date")
    args = ap.parse_args()
    text = render()
    if args.check:
        try:
            with open(HEADER) as f:
                current = f.read()
        except FileNotFoundError:
            current = ""
        if current != text:
            print(f"{HEADER} is out of date: run `make params`", file=sys.stderr)
            return 1
        print("gait_params.h matches the JSON files")
        return 0
    with open(HEADER, "w") as f:
        f.write(text)
    print(f"wrote {HEADER}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
